"""Profile the raw BigBasket CSV and write docs/data_profile_bigbasket.md.

Run: uv run python -m src.data.profile_bigbasket
"""

import re

import pandas as pd

from src.utils.log import get_logger
from src.utils.paths import REPO_ROOT, get_dir, load_config

log = get_logger(__name__)


def quantity_pattern(text: object) -> str:
    """Turn a Quantity string into a shape, e.g. '2 x 100 g' -> '# x # g', to see formats."""
    if pd.isna(text):
        return "<missing>"
    return re.sub(r"\d+(\.\d+)?", "#", str(text).strip().lower())


def build_profile(df: pd.DataFrame) -> str:
    """Return the profile as markdown text."""
    out: list[str] = [
        "# BigBasket data profile",
        "",
        "_Auto-generated by `src/data/profile_bigbasket.py`._",
        "",
    ]
    out += [f"- Rows: **{len(df):,}**", f"- Columns: **{df.shape[1]}**", ""]

    out += ["## Columns", "", "| column | dtype | null % | unique |", "|---|---|---|---|"]
    for col in df.columns:
        null_pct = df[col].isna().mean() * 100
        out.append(f"| {col} | {df[col].dtype} | {null_pct:.1f} | {df[col].nunique():,} |")

    out += ["", "## Sample rows (random, seed from config)", ""]
    seed = load_config()["random_seed"]
    out.append(df.sample(5, random_state=seed).to_markdown(index=False))

    out += ["", "## Categories and brands", ""]
    for col in ("Category", "SubCategory", "Brand"):
        if col in df.columns:
            out.append(f"- Unique `{col}`: **{df[col].nunique():,}**")

    if "Category" in df.columns:
        out += ["", "### Rows per Category", "", "| Category | rows |", "|---|---|"]
        for cat, n in df["Category"].value_counts().items():
            out.append(f"| {cat} | {n:,} |")

    if "Quantity" in df.columns:
        out += [
            "",
            "## Quantity formats (numbers replaced by #)",
            "",
            "| pattern | rows | example |",
            "|---|---|---|",
        ]
        shapes = df["Quantity"].map(quantity_pattern)
        for shape, n in shapes.value_counts().head(40).items():
            example = df.loc[shapes == shape, "Quantity"].iloc[0]
            out.append(f"| `{shape}` | {n:,} | {example} |")
        out.append(f"\nTotal distinct patterns: {shapes.nunique():,} (top 40 shown).")

    if {"Price", "DiscountPrice"}.issubset(df.columns):
        out += ["", "## Price columns", ""]
        out.append(df[["Price", "DiscountPrice"]].describe().to_markdown())
        higher = (df["DiscountPrice"] > df["Price"]).sum()
        equal = (df["DiscountPrice"] == df["Price"]).sum()
        lower = (df["DiscountPrice"] < df["Price"]).sum()
        out.append(
            f"\nRows where DiscountPrice > Price: **{higher:,}**; "
            f"equal: **{equal:,}**; lower: **{lower:,}**."
        )
    return "\n".join(out) + "\n"


def main() -> None:
    """Read the raw CSV and write the markdown profile."""
    cfg = load_config()
    csv_dir = get_dir("raw") / cfg["files"]["bigbasket_raw_dir"]
    csvs = sorted(csv_dir.glob("*.csv"))
    if not csvs:
        raise SystemExit(f"No CSV in {csv_dir}. Run `make a0` first.")
    df = pd.read_csv(csvs[0])
    out_path = REPO_ROOT / cfg["paths"]["docs"] / "data_profile_bigbasket.md"
    out_path.write_text(build_profile(df))
    log.info("Read %s (%d rows). Wrote %s", csvs[0].name, len(df), out_path)


if __name__ == "__main__":
    main()
